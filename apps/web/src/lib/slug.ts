/** สร้าง slug สำหรับ URL จากชื่อเรื่อง — ผู้ใช้จะได้ไม่ต้องคิดเอง
 *  ผลลัพธ์มีแค่ a-z, 0-9 และขีด ตามที่ฝั่งเซิร์ฟเวอร์บังคับไว้
 *
 *  ภาษาไทยจะถอดเป็นอักษรโรมันแบบประมาณ (อ่านออกพอให้เดาได้ว่าหน้าไหน)
 *  ไม่ได้ยึดหลักการถอดเสียงเป๊ะ ๆ เพราะ slug ต้องการแค่ อ่านรู้เรื่อง + คงที่ + ไม่ซ้ำ
 *  ถ้าอยากได้คำอื่นก็แก้ในช่องได้ตลอด */

/* พยัญชนะไทย → อักษรโรมัน (เสียงต้นพยางค์) */
const CONSONANTS: Record<string, string> = {
  ก: "k", ข: "kh", ฃ: "kh", ค: "kh", ฅ: "kh", ฆ: "kh", ง: "ng",
  จ: "ch", ฉ: "ch", ช: "ch", ซ: "s", ฌ: "ch", ญ: "y",
  ฎ: "d", ฏ: "t", ฐ: "th", ฑ: "th", ฒ: "th", ณ: "n",
  ด: "d", ต: "t", ถ: "th", ท: "th", ธ: "th", น: "n",
  บ: "b", ป: "p", ผ: "ph", ฝ: "f", พ: "ph", ฟ: "f", ภ: "ph", ม: "m",
  ย: "y", ร: "r", ล: "l", ว: "w",
  ศ: "s", ษ: "s", ส: "s", ห: "h", ฬ: "l", อ: "o", ฮ: "h",
};

/* สระและตัวเลขไทย */
const VOWELS: Record<string, string> = {
  "ะ": "a", "ั": "a", "า": "a", "ๅ": "a", "ำ": "am",
  "ิ": "i", "ี": "i", "ึ": "ue", "ื": "ue",
  "ุ": "u", "ู": "u",
  "เ": "e", "แ": "ae", "โ": "o", "ใ": "ai", "ไ": "ai", "ๆ": "",
  "๐": "0", "๑": "1", "๒": "2", "๓": "3", "๔": "4",
  "๕": "5", "๖": "6", "๗": "7", "๘": "8", "๙": "9",
};

/* วรรณยุกต์และเครื่องหมายที่ไม่ออกเสียง — ตัดทิ้ง
   (์ = ทัณฑฆาต ทำให้พยัญชนะก่อนหน้าไม่ออกเสียง แต่ที่นี่แค่ตัดตัวมันเอง) */
const SILENT = /[็-๎ฺ๏๚๛]/g;

/* ถอดทีละตัวอักษร ไม่ได้แยกพยางค์
   ภาษาไทยไม่เขียนสระเสียงสั้น ผลจึงเป็นคำที่อ่านได้คร่าว ๆ เท่านั้น
   (การถอดให้ถูกหลักต้องแยกพยางค์ก่อน ซึ่งต้องใช้พจนานุกรม — เกินจำเป็นสำหรับ slug)
   ทางที่ได้ URL สวยที่สุดคือกรอกชื่อภาษาอังกฤษไว้ ระบบจะใช้อันนั้นแทน */
function romanizeThai(input: string): string {
  let out = "";
  for (const ch of input.replace(SILENT, "")) {
    if (CONSONANTS[ch] !== undefined) out += CONSONANTS[ch];
    else if (VOWELS[ch] !== undefined) out += VOWELS[ch];
    else out += ch; // อักษรอื่น (อังกฤษ/ตัวเลข/ช่องว่าง) ปล่อยให้ขั้นตอนถัดไปจัดการ
  }
  return out;
}

/** แปลงข้อความใด ๆ เป็น slug — คืนค่าว่างถ้าไม่เหลืออะไรใช้ได้ */
export function slugify(text: string): string {
  return romanizeThai(text)
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "") // ตัดเครื่องหมายเสริมสระของภาษาละติน (é → e)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

/** เลือกต้นทางที่ดีที่สุดสำหรับสร้าง slug
 *  ใช้ชื่อภาษาอังกฤษก่อนถ้ามี เพราะได้ URL ที่อ่านง่ายกว่าการถอดเสียงไทย */
export function slugFrom(th: string, en?: string | null): string {
  return slugify(en?.trim() ? en : th);
}
